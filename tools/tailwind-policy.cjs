  prefixes.flatMap((prefix) => values.map((value) => `${prefix}-${value}`));

const pairClasses = (prefixes, values) =>
  prefixes.flatMap((prefix) =>
    values.flatMap((first) => values.map((second) => `${prefix}-${first}-${second}`)),
  );

