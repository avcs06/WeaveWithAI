import type { ClassRule } from '../../classname-adapter.js';

/** A class the repository's Tailwind configuration doesn't generate does nothing. */
export const unknownClass: ClassRule = (className, { policy }) =>
  policy.isValidClass && !policy.isValidClass(className)
    ? { rule: 'restricted-class', message: `"${className}" is not generated by the repository Tailwind configuration.` }
    : undefined;
